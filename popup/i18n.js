export function message(key, substitutions = {}) {
  substitutions = { minutePlural: Number(substitutions.minutes) === 1 ? "" : "s", hourPlural: Number(substitutions.hours) === 1 ? "" : "s", ...substitutions };
  const template = MESSAGES[activeLanguage][key] || MESSAGES.en[key] || key;

  return Object.entries(substitutions).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  );
}

export function setLanguage(language) {
  activeLanguage = language === "en" ? "en" : "zh";
}

export function applyMessages(root) {
  const documentNode = root.nodeType === Node.DOCUMENT_NODE ? root : root.ownerDocument;

  if (documentNode?.documentElement) {
    documentNode.documentElement.lang = activeLanguage === "zh" ? "zh-CN" : "en";
    documentNode.title = message("documentTitle");
  }

  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = message(node.dataset.i18n);
  }

  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    node.setAttribute("placeholder", message(node.dataset.i18nPlaceholder));
  }

  for (const node of root.querySelectorAll("[data-i18n-aria-label]")) {
    node.setAttribute("aria-label", message(node.dataset.i18nAriaLabel));
  }

  for (const node of root.querySelectorAll("[data-i18n-title]")) {
    node.setAttribute("title", message(node.dataset.i18nTitle));
  }
}
